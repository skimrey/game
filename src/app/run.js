export function standaloneLevel() {
  const difficulty = Math.max(0, Math.min(1, Number(params.get('difficulty') ?? 0.5)));
  const level = generateLevel({ seed: Number(params.get('seed')) || 1, difficulty }).level;
  level.tier = tierForDifficulty(difficulty).id;
  return level;
}

// --- Runs (roguelite) -------------------------------------------------------------
// Every run plays new layouts and new bosses: the hand-written campaign remixed and
// re-generated by a worker (levels/runLevels.js — every level re-checked by the audits) and
// bosses generated from the run seed (progression/bosses.js). Until a level's remix is ready, the
// hand-written level stands in.
export const newRunSeed = () => 1 + Math.floor(Math.random() * 999999);

// The run's journey: the zone each stage is played in (world/zones.js). ?zones=lagoon,grove,volcano,crystal picks one.
const stageOf = level => Math.max(0, TIERS.findIndex(t => t.id === level.tier));

                     // the rift level being played for an NPC's quest
export function journeyFor(seed) {
  const forced = (params.get('zones') || '').split(',').filter(id => ZONE_IDS.includes(id));
  const planned = planZones(seed, TIERS.length, { avoid: G.runZones });
  return TIERS.map((t, i) => forced[i] || planned[i]);
}

const inZone = level => (params.has('seed') ? level : { ...level, zone: G.runZones[stageOf(level)] });

                 // the hearts and technique pips (ui/hud.js)
// which mini-game each level's boss (and arcade checkpoint, if any) plays this run — see progression/encounters.js
const campaignSlots = () => TIERS.flatMap((t, k) => t.levels.map((_, i) => ({ tier: t.id, zone: G.runZones[k], slot: i, capstone: i === t.levels.length - 1 })));

                        // the gentle first run (progression/story.js): no class or spells, rift quests only
export function startRun(seed, { zones = null, gentle = false } = {}) {
  G.runSeed = seed;
  G.runZones = zones ? [...zones] : journeyFor(seed);
  G.runGentle = gentle;
  G.runSpells = gentle ? [] : [CLASSES[G.runClass].signature];
  G.hud?.setSpells(G.runGentle ? null : G.runClass, G.runSpells);
  G.npcPlan = params.has('seed') ? [] : planNpcs(seed || 1, TIERS.map(t => t.levels.length));
  npcs.clear(); npcState.clear(); G.npcActor = null; G.rift = null; G.stageBosses = [];
  campaign.splice(0, campaign.length, ...levels.map(inZone));
  G.renderer?.warmUp(G.runZones.flatMap(id => [BIOMES[ZONES[id].biome].material, BIOMES[ZONES[id].biome].ground?.material].filter(Boolean)), G.runZones.map(id => BIOMES[ZONES[id].biome]));
  runSources.fill('base');
  G.encounterPlan = params.has('seed') ? [] : planEncounters(G.runSeed, campaignSlots());
  runResults.clear();
  travelled.clear();
  G.runWorker?.terminate();
  G.runWorker = null;
  if (!G.runSeed || params.has('seed')) return;
  try {
    G.runWorker = new Worker(new URL('../levels/runWorker.js', import.meta.url), { type: 'module' });
    G.runWorker.onmessage = ({ data }) => {
      if (data.type === 'quest') { riftRequests.get(data.id)?.(data); riftRequests.delete(data.id); return; }
      if (data.type !== 'level') return;
      // only levels the player hasn't reached yet are swapped in
      if (data.index > G.levelIndex || (data.index === G.levelIndex && (!G.started || G.resuming))) {
        campaign[data.index] = inZone({ ...data.level, tier: levels[data.index].tier });
        runSources[data.index] = data.source;
      }
    };
    G.runWorker.onerror = error => { console.warn('Run worker failed — playing the hand-written levels', error.message); G.runWorker = null; };
    G.runWorker.postMessage({ type: 'start', runSeed: G.runSeed, want: G.levelIndex + 1 });
  } catch (error) {
    console.warn('No run worker — playing the hand-written levels', error);
  }
}

// --- Run results: every mini-game beaten (bosses, checkpoints, travel) → stars at the end
export function recordResult(role, won) {
  const key = `${G.levelIndex}:${role}`;
  runResults.set(key, runResults.get(key) || won);
  saveRun();
}

// --- Save and resume (a run in progress lives in the profile: close the game, come back
// through the portal, carry on from the start of the level you were on) ----------------------
export function saveRun() {
  if (!hubFirst || !G.runSeed || G.finished || G.inTown || G.rift || params.has('seed')) return;
  const stage = stageOf(campaign[G.levelIndex]);
  profile.saveRun({
    v: 1, runSeed: G.runSeed, runZones: G.runZones, runClass: G.runClass, runSpells: G.runSpells, gentle: G.runGentle, levelIndex: G.levelIndex,
    results: [...runResults], travelled: [...travelled], stageBosses: G.stageBosses || [],
    npcState: [...npcState].filter(([k]) => k < 100),
    label: `${ZONES[G.runZones[stage]]?.name || 'The run'} — level ${G.levelIndex + 1} of ${campaign.length}${G.runGentle ? '' : ` · ${CLASSES[G.runClass].name}, ${G.runSpells.length} spell${G.runSpells.length === 1 ? '' : 's'}`}`,
    savedAt: Date.now(),
  });
}

/** Back into a saved run: the same seed, zones, class, spells, results and quests; the level's start. */
export async function resumeRun(saved) {
  G.inTown = false;
  document.body.classList.remove('in-town');
  G.hud.setVisible(true);
  G.runClass = CLASS_IDS.includes(saved.runClass) ? saved.runClass : 'warrior';
  G.levelIndex = Math.max(0, Math.min(campaign.length - 1, saved.levelIndex | 0));
  G.resuming = true;
  startRun(saved.runSeed, { zones: saved.runZones, gentle: !!saved.gentle });
  G.runSpells = [...(saved.runSpells || [])];
  G.hud.setSpells(G.runGentle ? null : G.runClass, G.runSpells);
  for (const [k, v] of saved.results || []) runResults.set(k, v);
  for (const k of saved.travelled || []) travelled.add(k);
  G.stageBosses = Array.isArray(saved.stageBosses) ? saved.stageBosses : [];
  for (const [k, v] of saved.npcState || []) npcState.set(k, v);
  G.phase = 'resuming';
  panel.show({ kicker: 'The portal', title: 'Back through…', text: `Remaking the worlds of your run (${saved.label}). This takes a few seconds.`, buttons: [], accent: '#b58cff' });
  // the run worker remakes the levels in order; wait for this one (a hand-written level stands in after a while)
  const t0 = performance.now();
  while (G.runWorker && runSources[G.levelIndex] === 'base' && performance.now() - t0 < 30000) await new Promise(r => setTimeout(r, 200));
  G.resuming = false;
  panel.hide();
  G.started = true;
  G.phase = 'play';
  loadLevel(G.levelIndex);
  say(`Welcome back! ${saved.label}.`, 4);
  sound.fx('portal');
}

export function nextLevel() {
  panel.hide();
  reward.hide();
  document.body.classList.remove('in-stage');
  // the end of a stage: one of its beaten bosses may come home to the ranch (app/inn.js)
  // (only if you beat the stage's last boss — its capstone — otherwise nobody follows you home)
  if (campaignSlots()[G.levelIndex]?.capstone && G.stageBosses?.length) { G.phase = 'stage'; befriendAtStageEnd(() => nextLevel(), { capstoneBeaten: !!runResults.get(`${G.levelIndex}:boss`) }); return; }
  const trip = G.encounterPlan[G.levelIndex]?.travel;
  if (trip && battlesOn && !travelled.has(G.levelIndex)) { runTravel(trip); return; }
  G.phase = 'play';
  G.lastTime = undefined;
  G.renderer?.holdAdaptive(1000);
  if (G.levelIndex + 1 < campaign.length) loadLevel(G.levelIndex + 1);
  else finishRun();
}

/**
 * End of the run: stars for the games beaten — and, when you play from town, something to
 * take home: a decoration from the zones you visited (a perfect run: the trophy) and
 * sometimes a stray pet (three stars or more).
 */
export function finishRun() {
  G.finished = true;
  G.phase = 'play';
  const all = encounterList(G.encounterPlan);
  const beaten = all.filter(e => runResults.get(`${e.level}:${e.role}`)).length;
  const stars = starRating(beaten, all.length);
  try {
    const best = Number(localStorage.getItem('platformer.bestStars') || 0);
    if (stars > best) localStorage.setItem('platformer.bestStars', String(stars));
  } catch { /* private mode: no record */ }
  updateStatus();
  if (!all.length) return;
  const list = all.map(e => ({ label: MODES[e.mode].name, ok: !!runResults.get(`${e.level}:${e.role}`) }));
  if (!hubFirst) {
    panel.show({
      kicker: `Run ${G.runSeed} complete`, title: `${starsText(stars)}`,
      text: `${beaten} of ${all.length} games beaten${stars === 5 ? ' — a perfect run!' : ' — beat more for more stars.'}`,
      list, buttons: [['New run ▸', () => { panel.hide(); restart(); }, true]], accent: '#ffd23f',
    });
    return;
  }
  profile.finishRun(stars);
  profile.clearRun();
  const gold = 10 * stars + 2 * beaten;                 // gold: for the tailor (cosmetics only)
  profile.addGold(gold);
  // a pack of Riftcards for every finished run (better with more stars)
  const pack = openPack(mulberry32(hashSeed('run-pack', G.runSeed)), { faction: G.runZones.at(-1), tier: Math.min(5, profile.get().cardTier + Math.max(0, stars - 3)), n: stars >= 4 ? 4 : 3 });
  profile.addCards(pack);
  const decor = decorReward({ zones: G.runZones, stars, owned: profile.decor().map(d => d.id), seed: G.runSeed });
  if (decor) profile.addDecor(decor.id);
  const rng = mulberry32(hashSeed('stray', G.runSeed));
  const stray = stars >= 3 && rng() < 0.6 ? makePet(hashSeed('stray-pet', G.runSeed), { species: straySpecies(rng, stars) }) : null;
  const souvenir = `${decor ? ` You bring home a ${decor.name} for your house` : ' You come home'}, ${gold} gold and a pack of Riftcards: ${pack.map(id => CARDS[id].name).join(', ')}.`;
  panel.show({
    kicker: `Run ${G.runSeed} complete · ${CLASSES[G.runClass].name} · ${G.runSpells.length} spells`, title: `${starsText(stars)}`,
    text: `${beaten} of ${all.length} games beaten${stars === 5 ? ' — a perfect run!' : '.'}${souvenir}`,
    list,
    buttons: [['Home to town ▸', () => { panel.hide(); if (stray) offerStray(stray); else enterTown('portal'); }, true]],
    accent: '#ffd23f',
  });
}

/** A stray followed you home: adopt it? */
function offerStray(pet) {
  panel.show({
    kicker: 'Something followed you home…', title: `${pet.name} the ${SPECIES[pet.species].name.toLowerCase()}`,
    art: petCanvas(pet, { pose: 'cheer', scale: 6 }),
    text: `A ${pet.rarity} ${SPECIES[pet.species].name.toLowerCase()} has been tagging along since the last stage. It looks at you hopefully.`,
    buttons: [
      [`Adopt ${pet.name}`, () => { profile.adopt(pet); if (!pet || !profile.activePet()) profile.setActivePet(pet.id); setPet(profile.activePet()); panel.hide(); enterTown('portal'); say(`${pet.name} moved in! Visit the pet bed at home to choose who comes along.`, 5); }, true],
      ['Not this time', () => { panel.hide(); enterTown('portal'); }],
    ],
    accent: '#ff9de2',
  });
}

export function restart() {
  if (G.finished && hubFirst) { panel.hide(); enterTown('portal'); return; }   // the run is over: back to town
  if (G.finished) {                       // the run is over: a new one, with new layouts and bosses
    G.finished = false;
    G.levelIndex = 0;
    startRun(params.has('run') ? G.runSeed : newRunSeed());
    loadLevel(0);
    return;
  }
  loadLevel(G.levelIndex);
}
