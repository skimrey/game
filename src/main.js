// --- Runs (roguelite) -------------------------------------------------------------
// Every run plays new layouts and new bosses: the hand-written campaign remixed and
// re-generated by a worker (runLevels.js — every level re-checked by the audits) and
// bosses generated from the run seed (bosses.js). Until a level's remix is ready, the
// hand-written level stands in.
const newRunSeed = () => 1 + Math.floor(Math.random() * 999999);
let runSeed = params.has('run') ? Math.max(0, Math.floor(Number(params.get('run')) || 0)) : benchSeconds || params.has('seed') ? 0 : newRunSeed();
const campaign = params.has('seed') ? [standaloneLevel()] : [...levels];
const runSources = campaign.map(() => 'base');
let runWorker = null;
// which mini-game each level's boss (and arcade checkpoint, if any) plays this run — see encounters.js
const campaignSlots = () => TIERS.flatMap(t => t.levels.map((_, i) => ({ tier: t.id, slot: i, capstone: i === t.levels.length - 1 })));
let encounterPlan = [];
const runResults = new Map();                 // `${level}:${role}` → won: bosses, checkpoints, travel (stars at the end)
const travelled = new Set();                  // levels whose trip to the next region is done
function startRun(seed) {
  runSeed = seed;
  campaign.splice(0, campaign.length, ...levels);
  runSources.fill('base');
  encounterPlan = params.has('seed') ? [] : planEncounters(runSeed, campaignSlots());
  runResults.clear();
  travelled.clear();
  runWorker?.terminate();
  runWorker = null;
  if (!runSeed || params.has('seed')) return;
  try {
    runWorker = new Worker(new URL('./runWorker.js', import.meta.url), { type: 'module' });
    runWorker.onmessage = ({ data }) => {
      if (data.type !== 'level') return;
      // only levels the player hasn't reached yet are swapped in
      if (data.index > levelIndex || (data.index === levelIndex && !started)) {
        campaign[data.index] = { ...data.level, tier: levels[data.index].tier };
        runSources[data.index] = data.source;
      }
    };
    runWorker.onerror = error => { console.warn('Run worker failed — playing the hand-written levels', error.message); runWorker = null; };
    runWorker.postMessage({ type: 'start', runSeed, want: levelIndex + 1 });
  } catch (error) {
    console.warn('No run worker — playing the hand-written levels', error);
  }
}
