async function runBattle() {
  phase = 'battle';
  document.body.classList.add('in-battle');
  const level = campaign[levelIndex];
  const boss = bossForCurrentLevel();
  const { won } = await battle.start({ boss, design: currentDesign, seed: hashSeed('battle', runSeed, level.name, battleTries++), levelName: level.name });
  recordResult('boss', won);
  document.body.classList.remove('in-battle');
  lastTime = undefined;
  renderer?.holdAdaptive(1500);       // the 3D view was idle during the battle: not a slow frame
  if (won) {
    // tougher bosses drop rarer things: the region's row of the drop table, one row up for its capstone
    const item = characters.rollReward(Math.random, { region: Math.max(0, TIERS.findIndex(t => t.id === level.tier)), capstone: boss.capstone });
    if (item) characters.unlock(item.id);
    showStage({ boss, item, won: true });
  } else {
    showStage({ boss, item: null, won: false });
  }
}

/** The stage between levels (2D, like the battle): the hero and the won item on pedestals, or a level completed without a reward. */
function showStage({ boss, item, won }) {
  phase = 'stage';
  document.body.classList.add('in-stage');
  reward.show({ design: currentDesign, boss, item, won, seed: hashSeed('reward', runSeed, levelIndex) });
  const last = levelIndex + 1 >= campaign.length;
  const next = [last ? 'Finish ▸' : `Next level ▸`, () => nextLevel(), true];
  const wardrobe = ['Wardrobe', () => {
    panel.hide();
    reward.hide();
    document.body.classList.remove('in-stage');
    continueAfterMenu = true;
    openCharacterScreen({ wardrobe: true, label: last ? 'Finish' : `Continue to level ${levelIndex + 2}` });
  }];
  if (won && item) {
    const wear = ['Wear it', button => {
      currentDesign = { ...currentDesign, [item.slot]: item.value };
      if (currentDesign.id !== DRAFT_ID && characters.get(currentDesign.id) && !characters.isDefault(currentDesign.id)) characters.save(currentDesign);
      else { currentDesign = { ...currentDesign, id: DRAFT_ID }; characters.setDraft(currentDesign); characters.select(DRAFT_ID); }
      avatar.setCharacter(currentDesign);
      reward.setDesign(currentDesign);
      button.textContent = 'Wearing it ✓';
      button.disabled = true;
    }];
    panel.show({ kicker: `${boss.name} defeated · ${RARITY_INFO[item.rarity].label} item!`, title: item.name, text: item.about, buttons: [wear, wardrobe, next], accent: RARITY_INFO[item.rarity].color });
  } else if (won) {
    panel.show({ kicker: `${boss.name} defeated`, title: 'You’ve won every piece of clothing!', text: 'Mix and match them in the wardrobe.', buttons: [wardrobe, next] });
  } else {
    panel.show({ kicker: 'Level complete', title: 'No reward this time', text: `${boss.name} got away. Beat it to win a new piece of clothing.`,
      buttons: [['Fight again', () => { panel.hide(); reward.hide(); document.body.classList.remove('in-stage'); runBattle(); }], wardrobe, next] });
  }
}

function nextLevel() {
  panel.hide();
  reward.hide();
  document.body.classList.remove('in-stage');
  const trip = encounterPlan[levelIndex]?.travel;
  if (trip && battlesOn && !travelled.has(levelIndex)) { runTravel(trip); return; }
  phase = 'play';
  lastTime = undefined;
  renderer?.holdAdaptive(1000);
  if (levelIndex + 1 < campaign.length) loadLevel(levelIndex + 1);
  else finishRun();
}

// --- Travel levels: a vehicle trip between regions (raft, mine cart, snowmobile, biplane)
async function runTravel(trip) {
  phase = 'battle';
  document.body.classList.add('in-battle');
  controls.clear();
  const from = TIERS.find(t => t.id === trip.from), to = TIERS.find(t => t.id === trip.to);
  const ride = makeBoss({ runSeed, index: levelIndex, count: campaign.length, tier: trip.to, mode: trip.mode, role: 'travel', difficulty: trip.difficulty });
  const { won } = await battle.start({ boss: ride, design: currentDesign, seed: hashSeed('travel', runSeed, levelIndex), levelName: `${from?.name} → ${to?.name}` });
  recordResult('travel', won);
  travelled.add(levelIndex);
  document.body.classList.remove('in-battle');
  say(won ? `You made it to ${to?.name}!` : `You walked the long way round to ${to?.name}.`, 3);
  nextLevel();
}

/** End of the run: stars for the games beaten. */
function finishRun() {
  finished = true;
  phase = 'play';
  const all = encounterList(encounterPlan);
  const beaten = all.filter(e => runResults.get(`${e.level}:${e.role}`)).length;
  const stars = starRating(beaten, all.length);
  try {
    const best = Number(localStorage.getItem('platformer.bestStars') || 0);
    if (stars > best) localStorage.setItem('platformer.bestStars', String(stars));
  } catch { /* private mode: no record */ }
  updateStatus();
  if (!all.length) return;
  const list = all.map(e => ({ label: MODES[e.mode].name, ok: !!runResults.get(`${e.level}:${e.role}`) }));
  panel.show({
    kicker: `Run ${runSeed} complete`,
    title: `${starsText(stars)}`,
    text: `${beaten} of ${all.length} games beaten${stars === 5 ? ' — a perfect run!' : ' — beat more for more stars.'}`,
    list,
    buttons: [['New run ▸', () => { panel.hide(); restart(); }, true]],
    accent: '#ffd23f',
  });
}

function updateShowroom(dt) {
  show.time += dt;
  show.clock += dt;
  const cycle = SHOWCASE.reduce((s, [, d]) => s + d, 0);
  let t = show.time % cycle;
  let preview = 'idle';
  for (const [name, d] of SHOWCASE) { if (t < d) { preview = name; break; } t -= d; }
  showAvatar.preview = preview;
  emitAvatarEffects(showAvatar.update(showPlayer, dt), particleSystem);   // dust while running in place
  // a trail shows off while the preview runs (as if moving: a point circling behind the hero)
  const design = showAvatar.design;
  if (design?.trail && design.trail !== 'none') {
    const a = show.time * 3;
    showTrail.update(design.trail, { x: Math.sin(a) * 0.4 - 0.3, y: preview === 'run' || preview === 'jump' ? 0.5 : 0.45, z: -0.5 + Math.cos(a) * 0.2 }, dt, particleSystem);
  }
}

/** Camera orbiting the hero, shifted so the hero sits in the middle of the space the panels leave free. */
function showroomCamera() {
  // the slow sway (see showAngle) shows off capes, packs and ponytails
  const a = showAngle(), pitch = 0.17, dist = 4.7;
  const target = [0, 0.78, 0];
  const eye = [target[0] + Math.sin(a) * Math.cos(pitch) * dist, target[1] + Math.sin(pitch) * dist, target[2] + Math.cos(a) * Math.cos(pitch) * dist];
  const { left, right, width } = screen.insets();
  const aspect = canvas.clientWidth / Math.max(1, canvas.clientHeight);
  const ndc = width ? ((left + (width - left - right) / 2) / width) * 2 - 1 : 0;   // where the hero should appear
  const shift = -ndc * dist * Math.tan(Math.PI / 6) * aspect;
  const rx = Math.cos(a), rz = -Math.sin(a);                                        // camera right (horizontal)
  for (const p of [eye, target]) { p[0] += rx * shift; p[2] += rz * shift; }
  return { eye, target };
}

function updateStatus() {
  const level = campaign[levelIndex];
  const bestTime = gameState.getStat('bestTimes')[level.name];
  const bestTimeStr = bestTime ? ` (Best: ${bestTime.toFixed(1)}s)` : '';

  const { tier } = environmentFor(level);
  const run = runSeed ? `Run ${runSeed} · ` : '';
  status.textContent = finished
    ? `${run}All ${campaign.length} levels complete — ${starsText(starRating(encounterList(encounterPlan).filter(e => runResults.get(`${e.level}:${e.role}`)).length, encounterList(encounterPlan).length))}! Press R for a new run.`
    : `${run}${tier.label} · ${tier.name} — Level ${levelIndex + 1}/${campaign.length}: ${level.name}${bestTimeStr}`;
  if (!finished) announceTier();
  // the controls for the techniques this region allows (abilities; bounce pads need no key)
  if (controlsLine) {
    const allowed = level.abilities || ['dash'];
    const jump = ['Space jump', allowed.includes('glide') && 'hold Space to glide', allowed.includes('double') && 'Space again in the air: double jump'].filter(Boolean).join(' · ');
    controlsLine.textContent = ['WASD / arrows move', jump, allowed.includes('dash') && 'Shift/J air dash', 'Q/K ground pound', 'R restart', 'C change hero'].filter(Boolean).join(' · ');
  }
}

function say(text, seconds = 2.5) {
  message = { text, until: performance.now() + seconds * 1000 };
  status.textContent = text;
}

function loadLevel(index) {
  levelIndex = index;
  runWorker?.postMessage({ type: 'want', index: index + 1 });   // plan one level ahead
  session = createSession(campaign[levelIndex]);
  avatar.reset(session.player);
  particleSystem.clear();
  levelStartTime = performance.now();
  benchTick = 0;
  setUpArcade();
  updateStatus();
  showHint(campaign[levelIndex]);
  testMenu?.refresh();
}

function restart() {
  if (finished) {                       // the run is over: a new one, with new layouts and bosses
    finished = false;
    levelIndex = 0;
    startRun(params.has('run') ? runSeed : newRunSeed());
    loadLevel(0);
    return;
  }
  loadLevel(levelIndex);
}

window.addEventListener('keydown', event => {
  if (screen.isOpen || phase !== 'play' || event.defaultPrevented || event.repeat || isTypingTarget(event.target)) return;
  if (event.code === 'KeyR') restart();
  if (event.code === 'KeyC' || event.code === 'Escape') { event.preventDefault(); openCharacterScreen(); }
});

function onEvents(events) {
  emitGameplayEffects(events, particleSystem);
  for (const e of events) {
    if (e.type === 'hurt' || e.type === 'fell') {
      hud.flash();
      if (e.type === 'fell' && e.health > 0) say(`Fell! ${e.health} heart${e.health === 1 ? '' : 's'} left.`);
    }
    if (e.type === 'death') {
      gameState.recordDeath();
      gameState.saveToLocalStorage();
      say('Out of hearts — restarting the level.');
    }
  }
}

