// --- Gem → boss battle → reward ------------------------------------------------
function collectGem() {
  const level = campaign[levelIndex];
  const levelTime = (performance.now() - levelStartTime) / 1000;
  gameState.updateLevelTime(level.name, levelTime);
  gameState.markLevelComplete(level.name);
  gameState.saveToLocalStorage();
  const { x, y, z } = level.goal;
  for (const color of [[1, 0.35, 0.85], [0.35, 0.9, 1], [1, 0.85, 0.3]]) {
    particleSystem.emit(x, y + 1.3, z, { count: 16, speed: 7, color, lifetime: 1.3 });
  }
  if (!battlesOn) { nextLevel(); return; }
  phase = 'gem';
  gemTimer = 1.1;
  battleTries = 0;
  say(`Gem collected in ${levelTime.toFixed(1)} s — a boss appears!`, 3);
}

/** The boss for the current level: generated from the run seed and the level's place in the campaign. */
function bossForCurrentLevel() {
  const level = campaign[levelIndex];
  const standalone = params.has('seed');
  const tier = TIERS.find(t => t.id === level.tier);
  const tierStart = tier ? TIERS.slice(0, TIERS.indexOf(tier)).reduce((n, t) => n + t.levels.length, 0) : 0;
  const slot = levelIndex - tierStart;
  const capstone = !!tier && !standalone && slot === tier.levels.length - 1;
  const planned = encounterPlan[levelIndex]?.boss;
  const forced = MODES[params.get('boss')] ? params.get('boss') : null;   // ?boss=<mini-game> forces one (see battle/index.js)
  return makeBoss({
    runSeed,
    index: standalone ? Math.round((level.meta?.difficulty ?? 0.5) * 11) : levelIndex,
    count: standalone ? 12 : campaign.length,
    tier: level.tier || 'meadow', slot, capstone,
    mode: forced || planned?.mode || null,
    iteration: forced ? 0 : planned?.iteration ?? 0,
    role: 'boss',
    difficulty: forced || !planned ? null : planned.difficulty,
  });
}

// --- Run results: every mini-game beaten (bosses, checkpoints, travel) → stars at the end
function recordResult(role, won) {
  const key = `${levelIndex}:${role}`;
  runResults.set(key, runResults.get(key) || won);
}

// --- Arcade checkpoints ------------------------------------------------------------
// Some levels have an arcade cabinet halfway (encounters.js decides which): its
// mini-game, won, saves a checkpoint there and refills the hearts.
let arcade = null;      // { spot, state: 'ready' | 'won' | 'done', checkpoint: { mode, iteration } }
function setUpArcade() {
  const planned = encounterPlan[levelIndex]?.checkpoint;
  arcade = null;
  if (!planned || benchSeconds || !battlesOn) return;
  const spot = placeArcade(campaign[levelIndex], environmentFor(campaign[levelIndex]).audit);
  if (spot) arcade = { spot, state: 'ready', checkpoint: planned };
}

async function runCheckpoint() {
  const level = campaign[levelIndex];
  const { mode, iteration, difficulty } = arcade.checkpoint;
  phase = 'battle';
  document.body.classList.add('in-battle');
  controls.clear();
  const pausedFrom = performance.now();
  const challenge = makeBoss({ runSeed, index: levelIndex, count: campaign.length, tier: level.tier || 'meadow', mode, iteration, role: 'checkpoint', difficulty });
  const { won } = await battle.start({ boss: challenge, design: currentDesign, seed: hashSeed('checkpoint', runSeed, level.name), levelName: level.name });
  recordResult('checkpoint', won);
  document.body.classList.remove('in-battle');
  levelStartTime += performance.now() - pausedFrom;          // the level clock doesn't run during the mini-game
  arcade.state = won ? 'won' : 'done';
  if (won) {
    session.save(arcade.spot);
    const { x, y, z } = arcade.spot;
    for (const color of [[1, 0.85, 0.3], [0.4, 0.9, 1]]) particleSystem.emit(x, y + 1.2, z, { count: 14, speed: 5, color, lifetime: 1 });
    say('Checkpoint saved — hearts refilled!', 3);
  } else say('No checkpoint this time — carry on!', 3);
  lastTime = undefined;
  renderer?.holdAdaptive(1500);
  phase = 'play';
}

