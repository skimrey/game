let renderer = null;
let lastTime;
let accumulator = 0;
try {
  const quality = resolveQuality(params);
  const render = createRenderer(canvas, quality);
  renderer = render;
  const meter = createFpsMeter(quality, { canvas, renderer: render });
  // ?warmup=S: seconds before measuring (e.g. to let adaptive quality settle)
  if (benchSeconds) meter.startBench(benchSeconds, Number(params.get('warmup')) || undefined).then(r => { status.textContent = `Bench: ${r.fps.toFixed(1)} fps avg · ${r.lowFps.toFixed(1)} low`; });
  // paint every tier's textures (and, in the test preset, bake every tier's sky) up
  // front so entering a new tier never hitches
  render.warmUp(TIERS.flatMap(t => [BIOMES[t.biome].material, BIOMES[t.biome].ground?.material].filter(Boolean)), TIERS.map(t => BIOMES[t.biome]));
  if (menuFirst) openCharacterScreen();
  else { setUpArcade(); updateStatus(); showHint(campaign[levelIndex]); }

  const step = 1 / 120;

  function renderShowroom(time) {
    let steps = 0;
    while (accumulator >= step && steps++ < 24) { updateShowroom(step); particleSystem.update(step); accumulator -= step; }
    if (controls.read().jump) screen.play();   // gamepad A starts too
    show.scenery ||= buildScenery(SHOWROOM, BIOMES.meadow, null);
    render(SHOWROOM_VIEW, showPlayer, particleSystem.getActiveParticles(), {
      avatar: showAvatar.getParts(showPlayer),
      shadow: computeShadow(SHOWROOM, showPlayer),
      camera: showroomCamera(),
      biome: BIOMES.meadow,
      scenery: sceneryForQuality(show.scenery, render.quality),
    });
    meter.frame(time);
    requestAnimationFrame(frame);
  }

  function frame(time) {
    performanceMonitor.beginFrame();
    performanceMonitor.beginUpdate();

    const frameDt = lastTime !== undefined ? Math.min((time - lastTime) / 1000, Config.MAX_DELTA_TIME) : 0;
    accumulator += frameDt;
    lastTime = time;

    if (screen.isOpen) { renderShowroom(time); return; }
    if (phase === 'battle' || phase === 'stage') { accumulator = 0; requestAnimationFrame(frame); return; }   // 2D screens draw themselves
    if (phase === 'gem') {
      gemTimer -= frameDt;
      if (gemTimer <= 0) runBattle();
    }

    while (accumulator >= step) {
      if (!finished && phase === 'play') {
        let input = controls.read();
        if (benchSeconds) {
          // Bench: replay the audit bot's verified solution (restart when it ends)
          const inputs = environmentFor(campaign[levelIndex]).audit.solution.inputs;
          if (benchTick >= inputs.length) { session.reset(); benchTick = 0; }
          input = decodeInput(inputs[benchTick++]);
        }

        const before = session.player;
        const { result, events } = session.step(input, step);
        onEvents(events);
        if (session.player !== before) avatar.reset(session.player);
        const pl = session.player;
        if (pl.sprung) {                       // a bounce pad: squash it, sparkle
          springBounces.set(pl.sprung, performance.now() / 1000);
          particleSystem.emit(pl.x, pl.y + 0.1, pl.z, { count: 10, speed: 4, color: [1, 0.55, 0.8], lifetime: 0.6 });
        }
        if (pl.doubled) particleSystem.emit(pl.x, pl.y, pl.z, { count: 12, speed: 3, color: [0.5, 0.85, 1], lifetime: 0.5 });

        if (result === 'goal' && benchSeconds) {
          session.reset();
          benchTick = 0;
        } else if (result === 'goal') {
          collectGem();
        } else if (arcade?.state === 'ready' && touchesArcade(session.player, arcade.spot)) {
          runCheckpoint();
          break;
        }
      }

      emitAvatarEffects(avatar.update(session.player, step), particleSystem);
      if (!blinkTrail()) trail.update(currentDesign.trail, session.player, step, particleSystem);
      particleSystem.update(step);
      accumulator -= step;
    }
    if (message && performance.now() > message.until) { message = null; updateStatus(); }

    performanceMonitor.endUpdate();
    performanceMonitor.beginRender();

    const level = campaign[levelIndex];
    const environment = environmentFor(level);
    const blink = session.invulnerable > 0 && Math.floor(session.time * 14) % 2 === 1;
    render(level, session.player, particleSystem.getActiveParticles(), {
      avatar: blink ? [] : avatar.getParts(session.player),
      shadow: computeShadow(level, session.player),
      hideGoal: phase === 'gem',             // collected: it burst into sparkles
      boxes: [
        ...session.enemyBoxes(enemyParts),
        ...(arcade ? arcadeBoxes(arcade.spot, time / 1000, arcade.state) : []),
        ...springBoxes(level, time / 1000, springBounces),
        ...(session.player.gliding ? gliderBoxes(session.player, hexToRgb(currentDesign.colors.hat)) : []),
      ],
      biome: environment.biome,
      scenery: sceneryForQuality(environment.scenery, render.quality),
      platformTint: environment.platformTint,
    });
    hud.update(session);

    performanceMonitor.endRender();
    performanceMonitor.endFrame();
    meter.frame(time);

    if (Config.SHOW_PERFORMANCE_STATS) {
      console.log(performanceMonitor.toString());
    }

    requestAnimationFrame(frame);
  }

  requestAnimationFrame(frame);
} catch (error) {
  status.textContent = `Unable to start: ${error.message}`;
  console.error(error);
}

