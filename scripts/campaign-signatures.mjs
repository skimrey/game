#!/usr/bin/env node
/**
 * Saves the hand-written campaign's level signatures (runLevels.signatureOf) to
 * src/campaignSignatures.js, so a run can start planning without re-auditing the
 * whole campaign first. Re-run after changing levels.js (a test checks it's current).
 *
 *   node scripts/campaign-signatures.mjs
 */
import { writeFileSync } from 'node:fs';
import { baseCampaign, signatureOf } from '../src/runLevels.js';
import { describeLevel } from '../src/campaignAudit.js';

const signatures = baseCampaign().map(slot => signatureOf(describeLevel(slot.level)));
const body = signatures.map(s => `  ${JSON.stringify(s)},`).join('\n');
writeFileSync(new URL('../src/campaignSignatures.js', import.meta.url),
  `// Generated by scripts/campaign-signatures.mjs — do not edit (test/run.test.js checks it).\nexport const CAMPAIGN_SIGNATURES = [\n${body}\n];\n`);
console.log(`saved ${signatures.length} signatures`);
